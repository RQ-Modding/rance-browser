# Checks that every rq.<module>.<call>( in lua_lines.h is a function of dist/lua/rq.lua, then
# writes a small C file the browser is built with (so the check runs on each build).
# Usage: check_lua_lines.py lua_lines.h rq.lua OUT.c
import re
import sys

header, rq_lua, out = sys.argv[1], sys.argv[2], sys.argv[3]
calls = sorted(set(re.findall(r"rq\.([a-z_]+)\.([a-z_]+)\(", open(header, encoding="utf-8").read())))
lua = open(rq_lua, encoding="utf-8").read()
missing = []
for module, name in calls:
    if not re.search(r"^function %s\.%s\(" % (re.escape(module), re.escape(name)), lua, re.M):
        missing.append("rq.%s.%s" % (module, name))
if missing:
    sys.stderr.write("lua_lines.h names calls rq.lua does not have: %s\n" % ", ".join(missing))
    sys.exit(1)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by check_lua_lines.py: %d calls checked against rq.lua */\n" % len(calls))
    f.write("const int rqb_lua_lines_checked = %d;\n" % len(calls))
