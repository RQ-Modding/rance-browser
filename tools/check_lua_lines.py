# Checks that every rq.<module>.<call>( in lua_lines.h is a function of RQ MOD's rq.lua, then writes
# a small C file the browser is built with (so the check runs on each build that has rq.lua), and a
# make-style dependency file naming both inputs (rq.lua is outside the project in RQ MOD's build).
# Without rq.lua (the browser built alone) nothing is checked and the count is 0.
# Usage: check_lua_lines.py OUT.c DEPFILE lua_lines.h [rq.lua]
import re
import sys


def depfile_path(p):
    return p.replace("\\", "/").replace(" ", "\\ ")


out, dep, header = sys.argv[1], sys.argv[2], sys.argv[3]
rq_lua = sys.argv[4] if len(sys.argv) > 4 and sys.argv[4] else None
calls = sorted(set(re.findall(r"rq\.([a-z_]+)\.([a-z_]+)\(", open(header, encoding="utf-8").read())))
checked = 0
if rq_lua:
    lua = open(rq_lua, encoding="utf-8").read()
    missing = []
    for module, name in calls:
        if not re.search(r"^function %s\.%s\(" % (re.escape(module), re.escape(name)), lua, re.M):
            missing.append("rq.%s.%s" % (module, name))
    if missing:
        sys.stderr.write("lua_lines.h names calls rq.lua does not have: %s\n" % ", ".join(missing))
        sys.exit(1)
    checked = len(calls)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by check_lua_lines.py: %d calls checked against rq.lua */\n" % checked)
    f.write("const int rq_lua_lines_checked = %d;\n" % checked)
with open(dep, "w", encoding="utf-8", newline="\n") as f:
    f.write("%s: %s%s\n" % (depfile_path(out), depfile_path(header), " " + depfile_path(rq_lua) if rq_lua else ""))
