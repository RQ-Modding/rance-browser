# Puts the games' profiles (games/*.tsv) into the program as one C table, each under its file's
# name without the extension (the game's code name, as its .ain is named).
# Usage: embed_games.py OUT.c IN.tsv...
import os
import sys

out, inputs = sys.argv[1], sys.argv[2:]
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by embed_games.py at compile, do not edit */\n")
    f.write("struct game_src { const char *code; const char *text; unsigned len; };\n")
    names = []
    for i, path in enumerate(inputs):
        data = open(path, "rb").read()
        code = os.path.splitext(os.path.basename(path))[0]
        names.append((code, i, len(data)))
        f.write("static const char game_%d[] = {\n" % i)
        for k in range(0, len(data), 16):
            f.write("\t" + ", ".join("0x%02x" % b for b in data[k:k + 16]) + ",\n")
        f.write("\t0\n};\n")
    f.write("const struct game_src game_srcs[] = {\n")
    for code, i, n in names:
        f.write('\t{ "%s", game_%d, %d },\n' % (code, i, n))
    f.write("\t{ 0, 0, 0 }\n};\n")
